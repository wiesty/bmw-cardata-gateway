// Changing any descriptor invalidates the container, even at the same count.
var containerName = descriptorContainerName(allDescriptors)

func descriptorContainerName(descriptors []string) string {
	sum := sha256.Sum256([]byte(strings.Join(descriptors, "\n")))
	return fmt.Sprintf("bmw-cardata-gateway-%x", sum[:6])
}
